def rich(s):
    """Light markup: ~~x~~ -> <del>, **x** -> <b>. Escapes everything else."""
    out, i = [], 0
    import re
    tokens = re.split(r"(~~.+?~~|\*\*.+?\*\*)", s)
    for t in tokens:
        if t.startswith("~~") and t.endswith("~~"):
            out.append(f'<del>{E(t[2:-2])}</del>')
        elif t.startswith("**") and t.endswith("**"):
            out.append(f'<b>{E(t[2:-2])}</b>')
        else:
            out.append(E(t))
    return "".join(out)

def cell(s, th=False, bg=None):
    tag = "th" if th else "td"
    attr = f' background-color="{bg}"' if bg else ""
    paras = "".join(f"<p>{rich(x)}</p>" for x in s.split("\n"))
    return f"<{tag}{attr}>{paras}</{tag}>"

def table(headers, rows, widths):
    cols = "".join(f'<col width="{w}"/>' for w in widths)
    h = "<tr>" + "".join(cell(x, th=True, bg="light-gray") for x in headers) + "</tr>"
    b = "".join("<tr>" + "".join(cell(c) for c in r) + "</tr>" for r in rows)
    return f"<table><colgroup>{cols}</colgroup><thead>{h}</thead><tbody>{b}</tbody></table>"

def p(s): return f"<p>{rich(s)}</p>"
def ul(items): return "<ul>" + "".join(f"<li>{rich(x)}</li>" for x in items) + "</ul>"
def ol(items): return "<ol>" + "".join(f"<li>{rich(x)}</li>" for x in items) + "</ol>"
def h(n, s): return f'<h{n}>{E(s)}</h{n}>'
def callout(lines, emoji="💡", bg="light-orange", border="orange"):
    return f'<callout emoji="{emoji}" background-color="{bg}" border-color="{border}">' + "".join(p(x) for x in lines) + "</callout>"

